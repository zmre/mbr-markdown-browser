/**
 * The pure half of `scripts/gen-icons.ts`: turns the icon source of truth
 * (`crates/mbr-core/templates/icons/*.svg`, inner shapes only) into the text
 * of `src/icon-shapes.ts`.
 *
 * Lives under `src/` so `icons.test.ts` can regenerate the module in memory
 * and fail when the checked-in copy is stale. Nothing in a bundle imports it.
 *
 * One named export per icon (`iconChevronRight`), never one object: Vite
 * tree-shakes unused named exports, so each bundle pays only for the icons it
 * draws.
 */

/** `chevron-right.svg` → `iconChevronRight`; `building-2.svg` → `iconBuilding2`. */
export function exportNameFor(file: string): string {
  return (
    'icon' +
    file
      .replace(/\.svg$/, '')
      .split('-')
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join('')
  )
}

/** Only these elements, self-closed, may appear in an icon file. */
const SHAPES = /^(<(path|circle|rect|line|polyline|polygon|ellipse)\b[^<>']*\/>)+$/

/** The generated module's full text, from `{ 'x.svg': '<path …/>\n', … }`. */
export function renderIconShapesModule(files: Readonly<Record<string, string>>): string {
  const lines = Object.keys(files)
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .map((file) => {
      const shapes = files[file].trim()
      if (!SHAPES.test(shapes)) {
        throw new Error(`${file}: expected one line of self-closed shapes, got ${shapes}`)
      }
      return `export const ${exportNameFor(file)} = '${shapes}'`
    })
  return [
    '// GENERATED by components/scripts/gen-icons.ts from',
    '// crates/mbr-core/templates/icons/*.svg. Do not edit: change the .svg, then run',
    '// `bun scripts/gen-icons.ts`. icons.test.ts fails while this file is stale.',
    '//',
    '// Lucide icons (https://lucide.dev): ISC License, Copyright (c) 2026 Lucide Icons',
    '// and Contributors; Feather-derived shapes MIT, Copyright (c) 2013-present Cole',
    "// Bemis. Full notices: crates/mbr-core/templates/icons/LICENSE. `iconFootnote` is mbr's own.",
    '',
    ...lines,
    '',
  ].join('\n')
}
